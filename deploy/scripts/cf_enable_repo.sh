#!/usr/bin/env bash
# Enable ClusterFuzz PR fuzzing on a WiredMind2 repo with minimal setup.
#
# Usage:
#   ./cf_enable_repo.sh OWNER/REPO [--engine auto|atheris|libfuzzer] [--no-scaffold] [--dry-run]
#
# What it does:
#   1. Detects engine / existing harnesses (or scaffolds via llm_scaffold_harness.py)
#   2. Opens an enablement PR on the target repo (thin dispatch workflow + harness)
#   3. Sets Actions variables + CLUSTERFUZZ_DISPATCH_TOKEN secret on the target
#   4. Ensures CLUSTERFUZZ_CROSS_REPO_TOKEN on WiredMind2/clusterfuzz
#   5. Writes deploy/targets/<slug>.yaml on this farm checkout
#
# Requires: gh auth with repo+workflow scopes; farm host with this deploy tree.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEPLOY_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
ROOT_DIR="$(cd "${DEPLOY_DIR}/.." && pwd)"
CALLER_TEMPLATE="${DEPLOY_DIR}/workflows/fuzz-pr-caller.yml.template"
FARM_REPO="${FARM_REPO:-WiredMind2/clusterfuzz}"

ENGINE="auto"
SCAFFOLD=1
DRY_RUN=0
REPO=""

usage() {
  sed -n '2,14p' "$0" | sed 's/^# \?//'
  exit 2
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --engine) ENGINE="${2:-}"; shift 2 ;;
    --no-scaffold) SCAFFOLD=0; shift ;;
    --scaffold) SCAFFOLD=1; shift ;;
    --dry-run) DRY_RUN=1; shift ;;
    -h|--help) usage ;;
    -*)
      echo "error: unknown flag $1" >&2
      usage
      ;;
    *)
      if [[ -n "${REPO}" ]]; then
        echo "error: unexpected arg $1" >&2
        usage
      fi
      REPO="$1"
      shift
      ;;
  esac
done

if [[ -z "${REPO}" || "${REPO}" != */* ]]; then
  echo "error: pass OWNER/REPO" >&2
  usage
fi

if [[ ! -f "${CALLER_TEMPLATE}" ]]; then
  echo "error: missing ${CALLER_TEMPLATE}" >&2
  exit 1
fi

command -v gh >/dev/null || { echo "error: gh CLI required" >&2; exit 1; }
command -v git >/dev/null || { echo "error: git required" >&2; exit 1; }
command -v python3 >/dev/null || { echo "error: python3 required" >&2; exit 1; }

SLUG="$(echo "${REPO#*/}" | tr '[:upper:]' '[:lower:]' | sed 's/[^a-z0-9-]/-/g')"
TARGET_YAML="${DEPLOY_DIR}/targets/${SLUG}.yaml"
WORK="$(mktemp -d "${TMPDIR:-/tmp}/cf-enable.XXXXXX")"
cleanup() { rm -rf "${WORK}"; }
trap cleanup EXIT

log() { echo "==> $*"; }

log "Inspecting ${REPO}"
DEFAULT_BRANCH="$(gh repo view "${REPO}" --json defaultBranchRef --jq .defaultBranchRef.name)"
gh repo clone "${REPO}" "${WORK}/repo" -- --depth 1 --branch "${DEFAULT_BRANCH}" >/dev/null
REPO_ROOT="${WORK}/repo"

detect_engine() {
  local eng="$1"
  if [[ "${eng}" != "auto" ]]; then
    echo "${eng}"
    return
  fi
  if find "${REPO_ROOT}/fuzz" -type f -name '*_fuzzer.py' 2>/dev/null | grep -q .; then
    echo atheris
    return
  fi
  if [[ -x "${REPO_ROOT}/fuzz/build.sh" ]] \
    || grep -Rsl 'LLVMFuzzerTestOneInput' "${REPO_ROOT}" --include='*.c' --include='*.cc' --include='*.cpp' 2>/dev/null | head -1 | grep -q .; then
    echo libfuzzer
    return
  fi
  # Prefer Atheris for Python repos, else libFuzzer scaffold.
  if [[ -f "${REPO_ROOT}/pyproject.toml" || -f "${REPO_ROOT}/setup.py" ]] \
    || find "${REPO_ROOT}" -maxdepth 2 -name '*.py' | head -1 | grep -q .; then
    echo atheris
  else
    echo libfuzzer
  fi
}

ENGINE="$(detect_engine "${ENGINE}")"
log "Engine: ${ENGINE}"

NEED_SCAFFOLD=0
if [[ "${ENGINE}" == "atheris" ]]; then
  if ! find "${REPO_ROOT}/fuzz" -type f -name '*_fuzzer.py' 2>/dev/null | grep -q .; then
    NEED_SCAFFOLD=1
  fi
else
  if [[ ! -x "${REPO_ROOT}/fuzz/build.sh" ]]; then
    NEED_SCAFFOLD=1
  fi
fi

if [[ "${NEED_SCAFFOLD}" -eq 1 && "${SCAFFOLD}" -eq 0 ]]; then
  echo "error: no harness found and --no-scaffold set" >&2
  exit 1
fi

BRANCH="chore/clusterfuzz-enable"
PUSH_DIR="${WORK}/push"
gh repo clone "${REPO}" "${PUSH_DIR}" -- --depth 1 --branch "${DEFAULT_BRANCH}" >/dev/null
cd "${PUSH_DIR}"
git checkout -B "${BRANCH}"

mkdir -p .github/workflows
cp "${CALLER_TEMPLATE}" .github/workflows/fuzz-pr.yml

if [[ "${NEED_SCAFFOLD}" -eq 1 ]]; then
  log "Scaffolding ${ENGINE} harness"
  LLM_FUZZ_ENABLED="${LLM_FUZZ_ENABLED:-1}" \
    python3 "${SCRIPT_DIR}/llm_scaffold_harness.py" \
      --engine "${ENGINE}" \
      --out-dir "${PUSH_DIR}" \
      --repo-root "${REPO_ROOT}" >/dev/null
fi

# Target yaml content for farm
HARNESS_LINES=""
if [[ "${ENGINE}" == "atheris" ]]; then
  while IFS= read -r h; do
    HARNESS_LINES+="  - ${h}"$'\n'
  done < <(find fuzz -type f -name '*_fuzzer.py' | sort)
else
  HARNESS_LINES="  - fuzz/build.sh"$'\n'
fi

SKIP_INGEST="0"
if [[ "${ENGINE}" == "atheris" ]]; then
  SKIP_INGEST="1"
fi

cat > "${WORK}/target.yaml" <<EOF
# Generated by cf_enable_repo.sh
id: ${SLUG}
github: ${REPO}
engine: ${ENGINE}
fuzz_seconds: 60
harnesses:
${HARNESS_LINES}ui_url: http://127.0.0.1:9300
notes: Enabled via central repository_dispatch to ${FARM_REPO}
llm:
  enabled: true
  model: Qwen2.5-Coder:1.5b
  base_url: http://127.0.0.1:11434
  background: true
EOF

git add .github/workflows/fuzz-pr.yml
if [[ -d fuzz ]]; then
  git add fuzz
fi

if git diff --cached --quiet; then
  log "Nothing to commit in target repo (workflow already present?)"
else
  git commit -m "$(cat <<EOF
Enable ClusterFuzz PR fuzzing (central dispatch).

Adds a thin workflow that dispatches to ${FARM_REPO} for self-hosted timed fuzz,
plus a scaffolded harness when none existed.
EOF
)"
fi

TOKEN="$(gh auth token)"

if [[ "${DRY_RUN}" -eq 1 ]]; then
  log "DRY RUN — would push branch ${BRANCH}, open PR, set vars/secrets, write ${TARGET_YAML}"
  cat "${WORK}/target.yaml"
  exit 0
fi

log "Configuring secrets/vars on ${REPO}"
# Dispatch token: farm uses same PAT so target Actions can repository_dispatch.
gh secret set CLUSTERFUZZ_DISPATCH_TOKEN --repo "${REPO}" --body "${TOKEN}"

gh variable set FUZZ_ENGINE --repo "${REPO}" --body "${ENGINE}"
gh variable set FUZZ_SECONDS --repo "${REPO}" --body "60"
gh variable set CLUSTERFUZZ_UI_URL --repo "${REPO}" --body "http://127.0.0.1:9300"
gh variable set TARGET_ID --repo "${REPO}" --body "${SLUG}"
gh variable set LLM_FUZZ_ENABLED --repo "${REPO}" --body "1"
gh variable set LLM_FUZZ_BG_ENABLED --repo "${REPO}" --body "1"
gh variable set SKIP_INGEST --repo "${REPO}" --body "${SKIP_INGEST}"

log "Ensuring cross-repo token on ${FARM_REPO}"
gh secret set CLUSTERFUZZ_CROSS_REPO_TOKEN --repo "${FARM_REPO}" --body "${TOKEN}"

log "Pushing enablement branch"
git push -u origin "HEAD:${BRANCH}" --force-with-lease

PR_URL="$(gh pr list --repo "${REPO}" --head "${BRANCH}" --json url --jq '.[0].url // empty')"
if [[ -z "${PR_URL}" ]]; then
  PR_URL="$(gh pr create --repo "${REPO}" --base "${DEFAULT_BRANCH}" --head "${BRANCH}" \
    --title "Enable ClusterFuzz PR fuzzing" \
    --body "$(cat <<EOF
## Summary
- Adds \`.github/workflows/fuzz-pr.yml\` (dispatches to \`${FARM_REPO}\`)
- Engine: \`${ENGINE}\`${NEED_SCAFFOLD:+
- Scaffolds an initial fuzz harness under \`fuzz/\`}

## After merge
PRs on this repo will trigger timed fuzz on the ClusterFuzz host and post review comments when crashes are found.

Farm target id: \`${SLUG}\`
EOF
)" )"
fi

log "Writing farm target ${TARGET_YAML}"
cp "${WORK}/target.yaml" "${TARGET_YAML}"

log "Done"
echo "  Enablement PR: ${PR_URL}"
echo "  Farm target:   ${TARGET_YAML}"
echo "  Merge the PR, then open any PR on ${REPO} to exercise fuzzing."
echo "  If you use a GitHub Organization later, see deploy/workflows/fuzz-pr-org-caller.yml.template"
